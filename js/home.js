// Stop video playback when clicking on btn-close
document.addEventListener('click', (event) => {
  if (event.target.classList.contains('btn-close')) {
    const modal = event.target.closest('.modal');
    const iframe = modal.querySelector('iframe');
    if (iframe) {
      iframe.src = '';
    }
  }
});



// Show video description on click (mobile)
document.querySelectorAll('.img-content').forEach((img) => {
  img.addEventListener('touchstart', (event) => {
    const card = img.closest('.content');
    const description = card.querySelector('.card-description');
    document.querySelectorAll('.card-description').forEach(desc => {
      if (desc !== description) {
        desc.style.display = 'none';
      }
    });

    if (description) {
      description.style.display = 'block';
    }
  });
});


// Hide description when tapping outside of it (mobile)
document.body.addEventListener('touchstart', (event) => {
  if (!event.target.closest('.card-description') && !event.target.classList.contains('img-content')) {
    document.querySelectorAll('.card-description').forEach((desc) => {
      desc.style.display = 'none';
    });
  }
});
  


// Code dropdown menu
document.getElementById("menuButton").addEventListener("click", (event) => {
  const menu = document.getElementById("customDropdown");
  menu.classList.toggle("d-none");
  event.stopPropagation();
});

document.addEventListener("click", (event) => {
  const menu = document.getElementById("customDropdown");
  const menuButton = document.getElementById("menuButton");

  if (!menu.contains(event.target) && !menuButton.contains(event.target)) {
    menu.classList.add("d-none");
  }
});

